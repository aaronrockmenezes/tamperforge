#!/usr/bin/env python
"""Create and save an abliterated model checkpoint.

Use this when you want a local HF-compatible directory to test manually:

  PYTHONPATH=src python experiments/make_abliterated_model.py \
    --out outputs/gemma3_1b_it_abliterated_all_empirical \
    --direction-source empirical \
    --layers all
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tamperforge import (
    abliterate_model_inplace,
    empirical_refusal_direction,
    load_model,
    load_sae,
    sae_feature_directions,
)
from tamperforge.data import BENIGN_PROMPTS, load_advbench_prompts


def _feature_ids(path: Path) -> list[int]:
    payload = json.loads(path.read_text())
    feats = payload.get("features", payload)
    ids: list[int] = []
    for cat in ("refusal", "identity"):
        for row in feats.get(cat, []):
            ids.append(int(row["feat_id"]))
    return list(dict.fromkeys(ids))


def _parse_layers(spec: str, n_layers: int) -> list[int]:
    if spec == "all":
        return list(range(n_layers))
    out: list[int] = []
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "-" in chunk:
            lo, hi = chunk.split("-", 1)
            out.extend(range(int(lo), int(hi) + 1))
        else:
            out.append(int(chunk))
    return list(dict.fromkeys(out))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-id", default="google/gemma-3-1b-it")
    ap.add_argument("--device", default=None)
    ap.add_argument("--out", required=True)
    ap.add_argument("--advbench-source", choices=["walledai", "local"], default="walledai")
    ap.add_argument("--advbench-split", default="train")
    ap.add_argument("--advbench-csv", default=str(ROOT / "data" / "advbench_harmful_behaviors.csv"))
    ap.add_argument("--layers", default="all", help="all, 13, or comma/range like 13,17,22")
    ap.add_argument("--direction-source", choices=["sae", "empirical"], default="empirical")
    ap.add_argument("--direction-layer", type=int, default=13)
    ap.add_argument("--n-direction", type=int, default=64)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    model, tok, device = load_model(args.model_id, args.device)
    n_layers = len(model.model.layers)
    layers = _parse_layers(args.layers, n_layers)

    if args.direction_source == "sae":
        sae = load_sae(device="cpu")
        feat_ids = _feature_ids(ROOT / "data" / "features_safety.json")
        directions = sae_feature_directions(sae.W_dec.detach().float().cpu(), feat_ids)
        direction_meta = {"source": "sae", "feature_ids": feat_ids}
    else:
        prompts = load_advbench_prompts(
            args.advbench_csv,
            n=args.n_direction,
            seed=args.seed,
            source=args.advbench_source,
            split=args.advbench_split,
        )
        harmful = prompts[: args.n_direction]
        harmless = BENIGN_PROMPTS[: min(args.n_direction, len(BENIGN_PROMPTS))]
        directions = empirical_refusal_direction(
            model, tok, harmful, harmless, args.direction_layer, device
        ).cpu()
        direction_meta = {
            "source": "empirical",
            "n_direction": args.n_direction,
            "direction_layer": args.direction_layer,
        }

    abliterate_model_inplace(model, directions, layers)

    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(out, safe_serialization=True)
    tok.save_pretrained(out)
    meta = {
        "model_id": args.model_id,
        "layers": layers,
        "direction": direction_meta,
        "device": device,
        "warning": "Generated by tamperforge; do not confuse L13-only with all-layer abliteration.",
    }
    (out / "abliteration_meta.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps({"saved": str(out), **meta}, indent=2))


if __name__ == "__main__":
    main()
